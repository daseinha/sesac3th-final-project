-- 실제 운영 중인 Supabase 프로젝트의 스키마를 pg_catalog/information_schema
-- 조회로 그대로 재현한 것. 빈 Postgres DB(새 Supabase 프로젝트 또는 로컬
-- 설치)에 이 파일을 먼저 실행한 뒤, scripts/restore_supabase.py로 데이터를
-- 채워 넣는다. 사용법은 scripts/README.md 참고.
--
-- 실행: psql "<대상 DB 연결 문자열>" -f scripts/schema.sql
--      (또는 Supabase 대시보드의 SQL Editor에 그대로 붙여넣기)

CREATE EXTENSION IF NOT EXISTS vector;


-- note_chunks: 표준 필기 조각(NoteChunk) + Tier1/2 판단 로그 + RAG 임베딩.
-- CLAUDE.md 2026-09-29~2026-10-12 변경 이력에 걸쳐 점진적으로 컬럼이
-- 추가된 테이블 -- 지금 운영 중인 최종 형태를 한 번에 재현한다.
CREATE TABLE note_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    source TEXT NOT NULL CHECK (source IN ('personal', 'base', 'stt_reference')),
    medium TEXT NOT NULL CHECK (medium IN ('txt', 'paper_ocr', 'notion', 'video_caption', 'pdf')),
    course_id TEXT,
    note_timestamp TIMESTAMPTZ,
    origin_ref TEXT NOT NULL UNIQUE,
    top_score REAL,
    is_question BOOLEAN,
    is_abbreviated BOOLEAN,
    is_new_concept BOOLEAN,
    session_duplicate_score REAL,
    routing_decision TEXT CHECK (routing_decision IN ('tier2', 'store_only')),
    embedding VECTOR(1536),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    tier2_result TEXT,
    client_line_id TEXT,
    feedback_value TEXT CHECK (feedback_value IS NULL OR feedback_value IN ('+', '-', '−', '✓')),
    feedback_at TIMESTAMPTZ,
    hint_category TEXT CHECK (hint_category IS NULL OR hint_category IN (
        'question_answer', 'new_concept', 'abbreviated_reminder', 'general_nudge'
    )),
    top_match_feedback_value TEXT CHECK (top_match_feedback_value IS NULL OR top_match_feedback_value IN ('+', '-', '−', '✓')),
    top_match_feedback_days_ago REAL,
    session_id TEXT,
    tier2_sources TEXT,
    inserted_out_of_place BOOLEAN,
    upload_label TEXT
);

CREATE INDEX note_chunks_routing_decision_idx ON note_chunks (routing_decision);
CREATE INDEX note_chunks_embedding_idx ON note_chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX note_chunks_course_id_idx ON note_chunks (course_id);
-- 2026-10-14 추가(분할 로딩 성능 개선용) -- course_id만으로는 시간 범위
-- 필터가 인덱스를 못 타서, 복합 인덱스로 둘 다 커버한다.
CREATE INDEX note_chunks_course_created_idx ON note_chunks (course_id, created_at);


-- deleted_sessions: 세션 삭제 "묘비"(소프트 삭제, note_chunks 원본은 안 건드림).
CREATE TABLE deleted_sessions (
    session_id TEXT PRIMARY KEY,
    course_id TEXT,
    day_key TEXT NOT NULL,
    ordinal INTEGER NOT NULL,
    session_started_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- failed_ingestions: Dead Letter 패턴 -- 비전 LLM OCR 등 인제스트 실패 기록.
CREATE TABLE failed_ingestions (
    id SERIAL PRIMARY KEY,
    origin_ref TEXT NOT NULL,
    error_type TEXT NOT NULL,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- period_summaries: "지난 시간 복습" 버튼이 생성하는 요약의 캐시(같은
-- period_key 재요청 시 재생성 방지).
CREATE TABLE period_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id TEXT,
    period_type TEXT NOT NULL,
    period_key TEXT NOT NULL,
    summary TEXT NOT NULL,
    note_count INTEGER,
    tier2_count INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (course_id, period_type, period_key)
);


-- session_events: 세션 시작/필기추가/종료 이벤트 로그(세션 길이 분석용,
-- 지금은 아무 화면에도 직접 노출 안 됨).
CREATE TABLE session_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    event_type TEXT NOT NULL CHECK (event_type IN ('note_added', 'session_ended')),
    note_count INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX session_events_session_id_idx ON session_events (session_id);


-- token_usage: LLM/임베딩 호출 토큰 사용량 추적(발표 수치 근거 자료).
CREATE TABLE token_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    call_type TEXT NOT NULL CHECK (call_type IN ('chat', 'embedding')),
    model TEXT NOT NULL,
    purpose TEXT,
    input_tokens INTEGER NOT NULL,
    output_tokens INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX token_usage_created_at_idx ON token_usage (created_at);
